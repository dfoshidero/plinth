"""Checks on plinth's own repository tooling."""

import re
import subprocess
from pathlib import Path

import pytest

NO_AI = Path(__file__).resolve().parent.parent / ".github" / "workflows" / "no-ai.yml"


def _pattern() -> str:
    return re.search(r"pattern='(.+)'", NO_AI.read_text()).group(1)


@pytest.mark.parametrize(
    ("message", "flagged"),
    [
        ("Co-Authored-By: Claude <noreply@anthropic.com>", True),
        ("Generated with AI", True),
        ("generated by Copilot", True),
        ("Generated by the main release script", False),
        ("fix: retry failed pushes", False),
    ],
)
def test_no_ai_check(message, flagged):
    result = subprocess.run(
        ["grep", "-iE", _pattern()], input=message, capture_output=True, text=True, check=False
    )
    assert (result.returncode == 0) is flagged
