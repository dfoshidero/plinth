import shutil
import subprocess

import pytest

from plinth.commands.update import update_project
from plinth.model.loader import parse_config
from plinth.model.plan import build_plan
from plinth.output.render import BLUEPRINTS_DIR, render_plan
from plinth.output.write import write_project

pytestmark = pytest.mark.skipif(shutil.which("git") is None, reason="git not installed")


def git(path, *args):
    return subprocess.run(
        ["git", *args], cwd=path, capture_output=True, text=True, check=True
    ).stdout.strip()


@pytest.fixture
def project(tmp_path, config_dict, git_identity):
    plan = build_plan(parse_config(config_dict))
    root = tmp_path / "atlas"
    write_project(root, render_plan(plan), {r.folder: r.url for r in plan.repos}, init_git=True)
    return root


@pytest.fixture
def new_templates(tmp_path):
    """A copy of the blueprints with one template changed, standing in for a new plinth release."""
    copy = tmp_path / "blueprints"
    shutil.copytree(BLUEPRINTS_DIR, copy)
    target = copy / "repo" / "app" / "dot-gitignore"
    target.write_text(target.read_text() + "dist/\n")
    return copy


def statuses(result):
    return {r.folder: r.status for r in result.repos}


def test_nothing_to_do_right_after_generating(project):
    result = update_project(project)
    assert set(statuses(result).values()) == {"up to date"}


def test_template_changes_merge_and_keep_user_edits(project, new_templates):
    app = project / "atlas-app"
    readme = app / "README.md"
    readme.write_text(readme.read_text() + "\nmy notes\n")
    git(app, "commit", "-qam", "docs: my notes")

    result = update_project(project, new_templates)

    assert statuses(result)["atlas-app"] == "merged"
    assert "dist/" in (app / ".gitignore").read_text()
    assert "my notes" in readme.read_text()
    assert git(app, "status", "--porcelain") == ""


def test_conflicts_are_reported_not_hidden(project, new_templates):
    app = project / "atlas-app"
    (app / ".gitignore").write_text("mine\n")
    git(app, "commit", "-qam", "chore: my ignore file")

    result = update_project(project, new_templates)

    app_result = next(r for r in result.repos if r.folder == "atlas-app")
    assert app_result.status == "conflicts"
    assert ".gitignore" in app_result.conflicts


def test_dirty_repositories_are_skipped(project, new_templates):
    (project / "atlas-app" / "scratch.txt").write_text("wip")
    result = update_project(project, new_templates)
    assert statuses(result)["atlas-app"] == "skipped"
    assert "dist/" not in (project / "atlas-app" / ".gitignore").read_text()


def test_works_without_a_local_template_branch(project, new_templates):
    app = project / "atlas-app"
    git(app, "branch", "-D", "plinth")  # e.g. a project generated by plinth 0.2
    result = update_project(project, new_templates)
    assert statuses(result)["atlas-app"] == "merged"
